let currentLang = localStorage.getItem('lang') || 'zh-Hant';

function switchLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', 
    (lang === 'zh-Hant' && b.textContent.includes('繁')) ||
    (lang === 'zh-Hans' && b.textContent.includes('简')) ||
    (lang === 'en' && b.textContent.includes('EN'))
  ));
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const translations = T[lang] || T['zh-Hant'];
    const val = translations[key];
    if (val !== undefined) el.innerHTML = val;
  });
}
